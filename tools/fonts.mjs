#!/usr/bin/env node
// Vendor the game's web fonts so it plays with no network: the offline copy, the Godot port
// later, and a browser with Google blocked all get the same type.
//
//   node tools/fonts.mjs
//
// Reads the Google Fonts CSS URLs listed in FAMILIES below, keeps the Latin subset of each face,
// downloads the .woff2 files into prototype/web/fonts/, and writes prototype/web/fonts/fonts.css.
// Every family here is under the SIL Open Font License (prototype/web/fonts/OFL.txt), which
// allows bundling them with the game.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'prototype', 'web', 'fonts');

// One entry per Google Fonts css2 request, and the family's folder in github.com/google/fonts
// (for its license). Change the list, rerun, rebuild.
export const FAMILIES = [
  ['Newsreader:ital,opsz,wght@0,6..72,400;0,6..72,600;1,6..72,400', 'newsreader'],
  ['Barlow+Condensed:wght@400;500;600', 'barlowcondensed'],
  ['Big+Shoulders+Display:wght@300;600;800', 'bigshouldersdisplay'],
  ['Zilla+Slab:wght@400;600', 'zillaslab'],
  ['Anton', 'anton'],
  ['IBM+Plex+Mono:wght@400;500', 'ibmplexmono'],
  ['Cormorant+Garamond:ital,wght@1,400;1,500', 'cormorantgaramond'],
  ['Archivo+Black', 'archivoblack'],
  ['Work+Sans:wght@300;400', 'worksans'],
  ['Courier+Prime:wght@400;700', 'courierprime'],
  ['Kalam:wght@300;400', 'kalam'],
];

const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';

async function get(url, binary) {
  const r = await fetch(url, { headers: { 'user-agent': UA } });
  if (!r.ok) throw new Error(url + ': HTTP ' + r.status);
  return binary ? Buffer.from(await r.arrayBuffer()) : r.text();
}

function slug(s) { return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''); }

const css = [];
const licenses = [];
const byUrl = new Map();   // variable fonts: several weights share one file
let files = 0, bytes = 0;
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
for (const [fam, dir] of FAMILIES) {
  licenses.push(await get('https://raw.githubusercontent.com/google/fonts/main/ofl/' + dir + '/OFL.txt'));
  const src = await get('https://fonts.googleapis.com/css2?family=' + fam + '&display=swap');
  // Blocks look like: /* latin */ @font-face { ... }
  for (const m of src.matchAll(/\/\*\s*([a-z-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)) {
    if (m[1] !== 'latin') continue;
    let block = m[2];
    const family = /font-family:\s*'([^']+)'/.exec(block)[1];
    const style = /font-style:\s*(\w+)/.exec(block)[1];
    const weight = /font-weight:\s*([\d ]+)/.exec(block)[1].trim().replace(/\s+/g, '-');
    const url = /url\((https:[^)]+)\)/.exec(block)[1];
    let name = byUrl.get(url);
    if (!name) {
      name = `${slug(family)}-${weight}${style === 'italic' ? '-italic' : ''}.woff2`;
      const buf = await get(url, true);
      fs.writeFileSync(path.join(OUT, name), buf);
      byUrl.set(url, name);
      files++; bytes += buf.length;
    }
    block = block.replace(url, name);
    css.push(block.replace(/\n\s*/g, '\n  ').replace(/\n  \}$/, '\n}'));
  }
}
fs.writeFileSync(path.join(OUT, 'fonts.css'),
  '/* Generated by tools/fonts.mjs: the Latin subset of each face, bundled so the game needs no network.\n' +
  ' * All families are under the SIL Open Font License 1.1 (OFL.txt). */\n\n' + css.join('\n\n') + '\n');
fs.writeFileSync(path.join(OUT, 'OFL.txt'), licenses.map((t) => t.trim()).join('\n\n' + '-'.repeat(72) + '\n\n') + '\n');
console.log(`fonts: ${files} files, ${(bytes / 1024).toFixed(0)} KB, in ${path.relative(ROOT, OUT)}`);
